window.aevParseAmazon = function (raw) {
  const text = String(raw || "").trim();
  const out = { asin: "", search: "", host: "" };
  if (!text) return out;
  const host = text.match(/https?:\/\/((?:www\.)?amazon\.[a-z.]+)/i);
  if (host) out.host = host[1].toLowerCase();
  const dp = text.match(/\/(?:dp|gp\/product|gp\/aw\/d)\/([A-Z0-9]{10})/i);
  const bare = text.match(/\b([A-Z0-9]{10})\b/i);
  if (dp) out.asin = dp[1].toUpperCase();
  else if (/^[A-Z0-9]{10}$/i.test(text)) out.asin = text.toUpperCase();
  const q = text.match(/[?&]k=([^&]+)/i);
  if (!out.asin && q) out.search = decodeURIComponent(q[1].replace(/\+/g, " "));
  if (!out.asin && !out.search && !/^https?:/i.test(text) && text.length > 10) out.search = text;
  return out;
};

window.aevAmazonUrl = function (item) {
  const cfg = window.AEV || {};
  const tag = encodeURIComponent(cfg.amazonTag || "aguenvino07-20");
  let host = (cfg.amazonHost || "www.amazon.com").replace(/^https?:\/\//, "");
  const parsed = typeof item === "string" ? window.aevParseAmazon(item) : window.aevParseAmazon((item && (item.asin || item.url || item.search)) || "");
  if (item && typeof item === "object") {
    if (item.asin) parsed.asin = String(item.asin).toUpperCase().replace(/[^A-Z0-9]/g, "").slice(0, 10);
    if (item.search && !parsed.asin) parsed.search = item.search;
  }
  if (parsed.host) host = parsed.host;
  /* Formato que Amazon documenta para el bono de enlace directo */
  if (parsed.asin && parsed.asin.length === 10) {
    return "https://" + host + "/dp/" + parsed.asin + "/ref=nosim?tag=" + tag + "&linkCode=ll1&language=es_US";
  }
  const q = encodeURIComponent(parsed.search || (item && item.search) || "biblia de estudio");
  return "https://" + host + "/s?k=" + q + "&tag=" + tag + "&linkCode=ll2&language=es_US&ref=as_li_ss_tl";
};
